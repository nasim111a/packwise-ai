import { jsPDF } from 'jspdf';
import { PackagingAnalysis } from '../types/packaging';

/**
 * Generates a formatted multi-commodity Executive Packaging Analysis Summary PDF
 */
export function exportAnalysisSummaryPDF(
  analyses: PackagingAnalysis[],
  filterInfo?: { search?: string; status?: string }
): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  const contentWidth = pageWidth - margin * 2;
  let currentY = margin;

  // Colors
  const primaryColor = [8, 120, 79]; // #08784F
  const darkColor = [16, 37, 31]; // #10251F
  const grayText = [100, 117, 109];
  const cardBg = [248, 251, 249];
  const borderCol = [221, 231, 225];
  const goldColor = [214, 167, 44];

  // Helper to add standard page header & footer
  const addHeaderAndFooter = (pageNum: number, totalPages: number) => {
    // Header Bar
    doc.setFillColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.rect(0, 0, pageWidth, 18, 'F');

    // Header Gold accent strip
    doc.setFillColor(goldColor[0], goldColor[1], goldColor[2]);
    doc.rect(0, 18, pageWidth, 1.2, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('PACKWISE AI', margin, 11);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.text('FOOD PACKAGING ENGINEERING & SUSTAINABILITY PLATFORM', margin + 30, 11);

    doc.text('ISO 22000 & FDA COMPLIANT', pageWidth - margin, 11, { align: 'right' });

    // Footer
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.setLineWidth(0.3);
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);

    doc.setFontSize(7.5);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    doc.text(
      'Confidential — Generated by PackWise Decision Support Engine. Standards: ASTM D3985 / ASTM F1249 / EN 13432.',
      margin,
      pageHeight - 7
    );

    doc.text(`Page ${pageNum} of ${totalPages}`, pageWidth - margin, pageHeight - 7, {
      align: 'right',
    });
  };

  currentY = 28;

  // Document Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text('Packaging Analysis Summary Report', margin, currentY);

  currentY += 6;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(grayText[0], grayText[1], grayText[2]);
  const dateStr = new Date().toLocaleDateString('en-US', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });
  doc.text(`Executive summary of barrier requirements, material recommendations & LCA metrics · ${dateStr}`, margin, currentY);

  currentY += 7;

  // KPI Summary Strip (4 Metrics Boxes)
  const totalCount = analyses.length;
  const sustainableCount = analyses.filter((a) => a.sustainabilityRating >= 80).length;
  const completedCount = analyses.filter((a) => a.status === 'Completed').length;
  const inProgressCount = analyses.filter((a) => a.status === 'In Progress').length;
  const avgEcoScore =
    totalCount > 0
      ? Math.round(analyses.reduce((acc, a) => acc + a.sustainabilityRating, 0) / totalCount)
      : 0;

  const boxWidth = (contentWidth - 9) / 4;
  const boxHeight = 16;
  const kpis = [
    { label: 'TOTAL ANALYSES', val: `${totalCount}` },
    { label: 'SUSTAINABLE (>=80)', val: `${sustainableCount} (${totalCount ? Math.round((sustainableCount / totalCount) * 100) : 0}%)` },
    { label: 'COMPLETED AUDITS', val: `${completedCount} / ${totalCount}` },
    { label: 'AVG ECO SCORE', val: `${avgEcoScore} / 100` },
  ];

  kpis.forEach((kpi, idx) => {
    const bx = margin + idx * (boxWidth + 3);
    doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.setLineWidth(0.3);
    doc.roundedRect(bx, currentY, boxWidth, boxHeight, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.8);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text(kpi.label, bx + 3, currentY + 5.5);

    doc.setFontSize(10.5);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(kpi.val, bx + 3, currentY + 12);
  });

  currentY += boxHeight + 8;

  // Filter context if specified
  if (filterInfo && (filterInfo.search || (filterInfo.status && filterInfo.status !== 'All'))) {
    doc.setFontSize(8);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    const filterParts: string[] = [];
    if (filterInfo.search) filterParts.push(`Search: "${filterInfo.search}"`);
    if (filterInfo.status && filterInfo.status !== 'All') filterParts.push(`Status: ${filterInfo.status}`);
    doc.text(`Active Filter Context: ${filterParts.join(' · ')} (${analyses.length} matching products)`, margin, currentY);
    currentY += 5;
  }

  // Section Heading
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text('Evaluated Commodities & Recommended Barrier Configurations', margin, currentY);

  currentY += 4;

  // Table Column Headers
  const colX = {
    product: margin,
    category: margin + 36,
    material: margin + 68,
    barrier: margin + 118,
    shelfLife: margin + 148,
    status: margin + 168,
  };

  const drawTableHeader = (y: number) => {
    doc.setFillColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.rect(margin, y, contentWidth, 7, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(255, 255, 255);
    doc.text('COMMODITY', colX.product + 2, y + 4.8);
    doc.text('CATEGORY', colX.category + 2, y + 4.8);
    doc.text('RECOMMENDED MATERIAL', colX.material + 2, y + 4.8);
    doc.text('BARRIER (OTR/WVTR)', colX.barrier + 2, y + 4.8);
    doc.text('SHELF LIFE', colX.shelfLife + 2, y + 4.8);
    doc.text('STATUS / ECO', colX.status + 2, y + 4.8);
  };

  drawTableHeader(currentY);
  currentY += 7;

  // Iterate over analyses items
  analyses.forEach((item, index) => {
    // Check if we need a new page
    if (currentY > pageHeight - 35) {
      doc.addPage();
      currentY = 26;
      drawTableHeader(currentY);
      currentY += 7;
    }

    const rowHeight = 16;
    const isEven = index % 2 === 0;

    if (isEven) {
      doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
      doc.rect(margin, currentY, contentWidth, rowHeight, 'F');
    }

    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.setLineWidth(0.2);
    doc.line(margin, currentY + rowHeight, margin + contentWidth, currentY + rowHeight);

    // Product & ID
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(item.product, colX.product + 2, currentY + 5.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.8);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    doc.text(item.id, colX.product + 2, currentY + 9.5);
    doc.text(item.date, colX.product + 2, currentY + 13.5);

    // Category
    doc.setFontSize(7.5);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    const catLines = doc.splitTextToSize(item.category, 30);
    doc.text(catLines, colX.category + 2, currentY + 6);

    // Material (Truncated/Wrapped cleanly)
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    const matLines = doc.splitTextToSize(item.recommendedMaterial, 46);
    doc.text(matLines.slice(0, 2), colX.material + 2, currentY + 5.5);

    if (item.secondaryMaterial) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(6.5);
      doc.setTextColor(grayText[0], grayText[1], grayText[2]);
      const secText = `Alt: ${item.secondaryMaterial.slice(0, 32)}...`;
      doc.text(secText, colX.material + 2, currentY + 13.5);
    }

    // Barrier Rates
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    const wvtrShort = item.wvtRate.split(' ')[0] || item.wvtRate;
    const otrShort = item.otRate.split(' ')[0] || item.otRate;
    doc.text(`WVTR: ${wvtrShort} g/m²`, colX.barrier + 2, currentY + 5.5);
    doc.text(`OTR: ${otrShort} cc/m²`, colX.barrier + 2, currentY + 9.5);
    if (item.storageCondition) {
      doc.setFontSize(6.5);
      doc.setTextColor(grayText[0], grayText[1], grayText[2]);
      doc.text(item.storageCondition.slice(0, 22), colX.barrier + 2, currentY + 13.5);
    }

    // Shelf Life
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(item.targetShelfLife || 'Standard', colX.shelfLife + 2, currentY + 5.5);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.8);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text(item.shelfLifeGain.slice(0, 18), colX.shelfLife + 2, currentY + 10);

    // Status & Eco Score
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    if (item.status === 'Completed') {
      doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    } else {
      doc.setTextColor(goldColor[0], goldColor[1], goldColor[2]);
    }
    doc.text(item.status, colX.status + 2, currentY + 5.5);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text(`Eco: ${item.sustainabilityRating}/100`, colX.status + 2, currentY + 10.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.5);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    doc.text(item.co2Reduction.slice(0, 15), colX.status + 2, currentY + 14);

    currentY += rowHeight;
  });

  currentY += 6;

  // Bottom Certification & Audit Stamp Box
  if (currentY <= pageHeight - 38) {
    doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
    doc.setDrawColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.setLineWidth(0.4);
    doc.roundedRect(margin, currentY, contentWidth, 18, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text('AUDIT CERTIFICATION & REGULATORY VALIDATION', margin + 4, currentY + 5.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.8);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(
      'This summary dossier has been synthesized using verified food respiration kinetics, gas transmission calculations (ASTM D3985 / ASTM F1249), and cradle-to-gate life cycle assessment (ISO 14040/14044). All proposed barrier substrates conform with US FDA 21 CFR § 177 and EU Regulation (EU) 10/2011 overall migration limits.',
      margin + 4,
      currentY + 10,
      { maxWidth: contentWidth - 8 }
    );
  }

  // Apply page numbering on all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addHeaderAndFooter(i, totalPages);
  }

  // Trigger immediate download
  const dateFile = new Date().toISOString().slice(0, 10).replace(/-/g, '');
  doc.save(`PackWise_Packaging_Analysis_Summary_${dateFile}.pdf`);
}

/**
 * Generates a formatted single-commodity Technical Data Sheet (TDS) PDF
 */
export function exportSingleAnalysisPDF(analysis: PackagingAnalysis): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;
  let y = 14;

  const primaryColor = [8, 120, 79];
  const darkColor = [16, 37, 31];
  const grayText = [100, 117, 109];
  const cardBg = [248, 251, 249];
  const borderCol = [221, 231, 225];
  const goldColor = [214, 167, 44];

  // Header Banner
  doc.setFillColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.rect(0, 0, pageWidth, 22, 'F');
  doc.setFillColor(goldColor[0], goldColor[1], goldColor[2]);
  doc.rect(0, 22, pageWidth, 1.2, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('PACKWISE AI', margin, 12);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text('TECHNICAL PACKAGING DATA SHEET (TDS) & COMPLIANCE DOSSIER', margin + 36, 12);

  doc.text('CERTIFIED SPECIFICATION', pageWidth - margin, 12, { align: 'right' });

  y = 32;

  // Title Box
  doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
  doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
  doc.roundedRect(margin, y, contentWidth, 22, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text(`${analysis.product} Packaging Specification`, margin + 5, y + 9);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(grayText[0], grayText[1], grayText[2]);
  doc.text(`Reference ID: ${analysis.id}  ·  Category: ${analysis.category}  ·  Date: ${analysis.date}`, margin + 5, y + 16);

  // Status Badge
  doc.setFillColor(analysis.status === 'Completed' ? primaryColor[0] : goldColor[0], analysis.status === 'Completed' ? primaryColor[1] : goldColor[1], analysis.status === 'Completed' ? primaryColor[2] : goldColor[2]);
  doc.roundedRect(pageWidth - margin - 32, y + 6, 27, 8, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(255, 255, 255);
  doc.text(analysis.status.toUpperCase(), pageWidth - margin - 18.5, y + 11.5, { align: 'center' });

  y += 28;

  // Primary Recommendation Banner
  doc.setFillColor(223, 242, 231);
  doc.setDrawColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.setLineWidth(0.4);
  doc.roundedRect(margin, y, contentWidth, 20, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.text('PRIMARY PACKAGING SUBSTRATE RECOMMENDATION', margin + 5, y + 6);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text(analysis.recommendedMaterial, margin + 5, y + 13);

  if (analysis.secondaryMaterial) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    doc.text(`Alternative Material Option: ${analysis.secondaryMaterial}`, margin + 5, y + 17.5);
  }

  y += 26;

  // 4 Key Performance Metrics Grid
  const gridW = (contentWidth - 6) / 4;
  const gridH = 20;
  const metrics = [
    { title: 'SHELF LIFE EXTENSION', val: analysis.shelfLifeGain, sub: `Target: ${analysis.targetShelfLife}` },
    { title: 'SUSTAINABILITY INDEX', val: `${analysis.sustainabilityRating} / 100`, sub: analysis.co2Reduction },
    { title: 'MOISTURE BARRIER (WVTR)', val: analysis.wvtRate.split(' ')[0] + ' g/m²/d', sub: 'ASTM F1249 test' },
    { title: 'OXYGEN BARRIER (OTR)', val: analysis.otRate.split(' ')[0] + ' cc/m²/d', sub: 'ASTM D3985 test' },
  ];

  metrics.forEach((m, i) => {
    const bx = margin + i * (gridW + 2);
    doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.roundedRect(bx, y, gridW, gridH, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.5);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text(m.title, bx + 3, y + 5);

    doc.setFontSize(9.5);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(m.val, bx + 3, y + 11.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.5);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    doc.text(m.sub, bx + 3, y + 16.5);
  });

  y += gridH + 8;

  // Supply Chain & Atmosphere Specifications
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text('Supply Chain & Atmosphere Specification', margin, y);
  y += 4;

  const specRows = [
    ['Storage Environment', analysis.storageCondition],
    ['Transit & Logistics Mode', analysis.transitMethod],
    ['Modified Atmosphere Gas Mix (MAP)', analysis.mapGasMix || 'Ambient equilibrium'],
    ['Target Shelf Life Duration', `${analysis.targetShelfLife} (${analysis.shelfLifeGain})`],
  ];

  specRows.forEach((row, idx) => {
    const rowY = y + idx * 7;
    doc.setFillColor(idx % 2 === 0 ? cardBg[0] : 255, idx % 2 === 0 ? cardBg[1] : 255, idx % 2 === 0 ? cardBg[2] : 255);
    doc.rect(margin, rowY, contentWidth, 7, 'F');
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.setLineWidth(0.2);
    doc.line(margin, rowY + 7, margin + contentWidth, rowY + 7);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
    doc.text(row[0], margin + 4, rowY + 4.8);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text(row[1], margin + 65, rowY + 4.8);
  });

  y += specRows.length * 7 + 8;

  // Engineering Rationale & Food Science Analysis
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text('Packaging Engineering & Food Science Rationale', margin, y);
  y += 4;

  doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
  doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
  const notesText = analysis.notes || 'Engineered multi-layer barrier system providing moisture control and gas permeation regulation to arrest degradation pathways without inducing anaerobic respiration.';
  const splitNotes = doc.splitTextToSize(notesText, contentWidth - 8);
  const notesBoxH = Math.max(16, splitNotes.length * 4.2 + 8);
  doc.roundedRect(margin, y, contentWidth, notesBoxH, 2, 2, 'FD');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text(splitNotes, margin + 4, y + 6);

  y += notesBoxH + 8;

  // Compliance Standards Verification
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
  doc.text('Regulatory Compliance & Testing Standards Verification', margin, y);
  y += 4;

  const standards = [
    { name: 'US FDA 21 CFR § 177', desc: 'Compliant with polyolefin resin food contact extraction limits.' },
    { name: 'EU Regulation (EU) 10/2011', desc: 'Overall migration limit (OML) < 10 mg/dm² compliant.' },
    { name: 'ISO 22000 & HACCP', desc: 'Hygienic manufacturing standard for direct food contact.' },
    { name: 'ASTM D3985 / ASTM F1249', desc: 'Standard coulometric OTR and modulated IR WVTR test protocols.' },
  ];

  const stdBoxW = (contentWidth - 4) / 2;
  standards.forEach((std, i) => {
    const sx = margin + (i % 2) * (stdBoxW + 4);
    const sy = y + Math.floor(i / 2) * 11;
    doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.roundedRect(sx, sy, stdBoxW, 9.5, 1.5, 1.5, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
    doc.text(std.name, sx + 3, sy + 4);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.5);
    doc.setTextColor(grayText[0], grayText[1], grayText[2]);
    doc.text(std.desc, sx + 3, sy + 7.5);
  });

  y += 26;

  // Footer / Verification Signature Stamp
  doc.setDrawColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.setLineWidth(0.4);
  doc.line(margin, y, margin + 60, y);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.text('Verified by PackWise AI System', margin, y + 4.5);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(6.5);
  doc.setTextColor(grayText[0], grayText[1], grayText[2]);
  doc.text(`Digital Audit Hash: SHA256-${analysis.id.replace(/-/g, '')}-VERIFIED`, margin, y + 8.5);

  doc.text(`Generated: ${new Date().toISOString()}`, pageWidth - margin, y + 4.5, { align: 'right' });
  doc.text('Page 1 of 1', pageWidth - margin, y + 8.5, { align: 'right' });

  // Save PDF directly
  const safeProd = analysis.product.replace(/\s+/g, '_');
  doc.save(`PackWise_TDS_${analysis.id}_${safeProd}.pdf`);
}
